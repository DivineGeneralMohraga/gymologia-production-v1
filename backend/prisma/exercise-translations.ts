/**
 * Translated exercise content.
 *
 * The directory honours `Accept-Language` and has since the endpoint was
 * written, but until now only English rows existed, so every language got
 * English back. This is the content that closes that gap, one language at
 * a time.
 *
 * Two things are deliberate here.
 *
 * Names stay recognisable. A member who has heard "deadlift" on the gym
 * floor should find it under a name they can match to what the trainer
 * said, so lifts are transliterated rather than given invented Hindi
 * names. Yoga asanas go the other way: they already have Sanskrit names
 * that a Hindi reader knows better than the English gloss.
 *
 * Cautions are translated with more care than the steps. A vague step
 * costs a member a set; a vague caution costs them a shoulder. Where a
 * choice had to be made between a literal rendering and one that keeps
 * the warning unmistakable, the warning won.
 *
 * IMPORTANT: like the interface strings, these were written by an LLM and
 * not by a native speaker or a coach. They ship behind the same "pending
 * review" label, and the API marks each entry with whether the locale was
 * actually available so the app can say so.
 */

