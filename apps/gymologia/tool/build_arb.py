def build(locale: str, strings: dict) -> dict:
    out = {"@@locale": locale, "languageName": LANGUAGE_NAMES[locale]}
    for key, value in strings.items():
        if key.startswith("_"):
            continue
        out[key] = value

    zero, one, other = strings["_days"]
    out["daysRemaining"] = (
        "{count, plural, =0{%s} =1{%s} other{%s}}" % (zero, one, other)
    )
    one_w, other_w = strings["_weeks"]
    out["weeksRunning"] = "{count, plural, =1{%s} other{%s}}" % (one_w, other_w)

    # Placeholder strings carry their {name}/{gym} through unchanged.
    out["trainerNamed"] = strings["_trainer"]
    out["goalAtGym"] = strings["_goal"]
    out["takenOffList"] = strings["_off"]
    out["contactWithPhone"] = strings["_contact"]
    out["lastNDays"] = strings["_days_n"]
    out["markedPresent"] = strings["_present"]
    out["decidedBy"] = strings["_decided"]
    out["peakValue"] = strings["_peak"]
    out["removePerson"] = strings["_removePerson"]
    out["correctDate"] = strings["_correctDate"]
    out["deleteNamed"] = strings["_deleteNamed"]
    return out


def main() -> None:
    template = json.load(io.open(os.path.join(L10N, "app_en.arb"), encoding="utf-8"))
    expected = {k for k in template if not k.startswith("@")}

    for locale, strings in sorted(T.items()):
        data = build(locale, strings)
        path = os.path.join(L10N, "app_%s.arb" % locale)
        with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
            json.dump(data, handle, ensure_ascii=False, indent=2)
            handle.write("\n")

        missing = sorted(expected - set(data))
        note = "complete" if not missing else "%d fall back to English" % len(missing)
        print("%s  %3d strings  (%s)" % (locale, len(data) - 1, note))


if __name__ == "__main__":
    main()
